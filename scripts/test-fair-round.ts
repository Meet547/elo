import assert from 'node:assert/strict';
import {newFairRound,freezeFairParticipants,commitClientSeed,revealClientSeed,fairTranscript,publicFairRound,abortFairRound} from '../src/lib/poker/fair-round';
import {seedCommitment,deriveFairSeed} from '../src/lib/poker/fair-deck';
const round=newFairRound(),serverSeed=round.serverSeed;
const a='a'.repeat(64),b='b'.repeat(64);
assert.equal(round.phase,'waiting');assert(!JSON.stringify(publicFairRound(round)).includes(serverSeed));
assert.throws(()=>commitClientSeed(round,'a',a),/participant/);
assert.throws(()=>freezeFairParticipants(round,['a','a']),/participants/);
freezeFairParticipants(round,['a','b']);
assert.throws(()=>freezeFairParticipants(round,['a','c']),/frozen/);
assert.throws(()=>revealClientSeed(round,'a',a),/commit/);
const ca=seedCommitment('client',`${round.context}:a`,a),cb=seedCommitment('client',`${round.context}:b`,b);
commitClientSeed(round,'a',ca);commitClientSeed(round,'a',ca);
assert.throws(()=>commitClientSeed(round,'a',cb),/replaced/);
assert.throws(()=>revealClientSeed(round,'a',a),/commit/);
assert.throws(()=>commitClientSeed(round,'intruder',cb),/participant/);
commitClientSeed(round,'b',cb);assert.equal(round.phase,'revealing');
assert.throws(()=>revealClientSeed(round,'b',a),/commitment/);
revealClientSeed(round,'a',a);assert.throws(()=>fairTranscript(round),/incomplete/);
const partial=JSON.stringify(publicFairRound(round));assert(!partial.includes(a));assert(!partial.includes(b));assert(!partial.includes(serverSeed));
revealClientSeed(round,'b',b);revealClientSeed(round,'b',b);assert.equal(round.phase,'ready');
assert.throws(()=>revealClientSeed(round,'b',a),/replaced/);
const persisted=JSON.parse(JSON.stringify(round));
assert.equal(deriveFairSeed(fairTranscript(round),'hand-1'),deriveFairSeed(fairTranscript(persisted),'hand-1'));
assert.notEqual(deriveFairSeed(fairTranscript(round),'hand-1'),deriveFairSeed(fairTranscript(round),'hand-2'));
persisted.reveals.a=b;assert.throws(()=>fairTranscript(persisted),/commitment/);
abortFairRound(round);assert.throws(()=>fairTranscript(round),/incomplete/);assert.throws(()=>revealClientSeed(round,'a',a),/aborted/);assert.equal(round.serverSeed,serverSeed);
console.log('PASS — frozen participants, commit-before-reveal barrier, immutable inputs, persisted replay, per-hand context, private projection and fail-closed abort');

const unusual=newFairRound();freezeFairParticipants(unusual,['__proto__','toString']);
for(const id of unusual.participants)commitClientSeed(unusual,id,seedCommitment('client',`${unusual.context}:${id}`,a));
for(const id of unusual.participants)revealClientSeed(unusual,id,a);
assert.equal(unusual.phase,'ready');assert.doesNotThrow(()=>fairTranscript(JSON.parse(JSON.stringify(unusual))));
